'use strict';

const {
  Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell,
  AlignmentType, BorderStyle, WidthType, VerticalAlign,
  UnderlineType, convertInchesToTwip,
} = require('docx');
const fs   = require('fs');
const path = require('path');

// ─────────────────────────── FONT & SIZES ────────────────────────────────────
const F  = 'Arial';   // clean, readable
const SZ = {
  cover:  80,  // 40pt — εξώφυλλο τίτλος
  step:   64,  // 32pt — αριθμός βήματος
  title:  48,  // 24pt — τίτλος βήματος
  sub:    36,  // 18pt — υπό-τίτλος
  body:   30,  // 15pt — κείμενο
  small:  26,  // 13pt — σημειώσεις
};

// ─────────────────────────── BORDERS ─────────────────────────────────────────
const NO_BORDER = {
  top:    { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
  bottom: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
  left:   { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
  right:  { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
};
const BOX_BORDER = {
  top:    { style: BorderStyle.SINGLE, size: 12, color: '000000' },
  bottom: { style: BorderStyle.SINGLE, size: 12, color: '000000' },
  left:   { style: BorderStyle.THICK,  size: 28, color: '000000' },
  right:  { style: BorderStyle.SINGLE, size: 12, color: '000000' },
};
const THIN_BOX = {
  top:    { style: BorderStyle.SINGLE, size: 6, color: '000000' },
  bottom: { style: BorderStyle.SINGLE, size: 6, color: '000000' },
  left:   { style: BorderStyle.SINGLE, size: 6, color: '000000' },
  right:  { style: BorderStyle.SINGLE, size: 6, color: '000000' },
};
const STEP_LINE = {
  bottom: { style: BorderStyle.THICK, size: 20, color: '000000' },
};

// ─────────────────────────── HELPERS ─────────────────────────────────────────

// Κενή γραμμή
const sp = (pts = 120) =>
  new Paragraph({ spacing: { before: pts, after: 0 }, children: [] });

// Χωρισμός σελίδας
const pageBreak = () =>
  new Paragraph({ pageBreakBefore: true, children: [new TextRun({ text: '', font: F, size: SZ.body })] });

// Απλό κείμενο
function txt(text, sz = SZ.body, bold = false, italic = false) {
  return new TextRun({ text, font: F, size: sz, bold, italic, color: '000000' });
}

// Παράγραφος με σύνθετο κείμενο
function para(runs, align = AlignmentType.LEFT, before = 60, after = 40) {
  return new Paragraph({
    alignment: align,
    spacing:   { before, after },
    children:  Array.isArray(runs) ? runs : [runs],
  });
}

// Τίτλος Βήματος (με γραμμή κάτω)
function stepHeader(num, title) {
  return [
    new Paragraph({
      pageBreakBefore: true,
      spacing: { before: 0, after: 40 },
      border:  STEP_LINE,
      children: [
        new TextRun({ text: `ΒΗΜΑ ${num}`, font: F, size: SZ.step, bold: true, color: '000000' }),
        new TextRun({ text: `   ${title}`, font: F, size: SZ.title, bold: true, color: '000000' }),
      ],
    }),
    sp(60),
  ];
}

// Υπο-τίτλος
function subHdr(text) {
  return new Paragraph({
    spacing: { before: 160, after: 40 },
    children: [
      new TextRun({
        text,
        font: F, size: SZ.sub, bold: true, color: '000000',
        underline: { type: UnderlineType.SINGLE, color: '000000' },
      }),
    ],
  });
}

// Κείμενο σώματος
function body(text, before = 40, after = 30) {
  return new Paragraph({
    spacing: { before, after },
    children: [new TextRun({ text, font: F, size: SZ.body, color: '000000' })],
  });
}

// Βήμα με βέλος  →  1. Κάντε αυτό
function step(num, boldPart, rest = '') {
  return new Paragraph({
    spacing: { before: 60, after: 50 },
    indent:  { left: convertInchesToTwip(0.3) },
    children: [
      new TextRun({ text: `${num}.  `, font: F, size: SZ.body, bold: true }),
      new TextRun({ text: boldPart, font: F, size: SZ.body, bold: true, color: '000000' }),
      ...(rest ? [new TextRun({ text: `  ${rest}`, font: F, size: SZ.body, color: '000000' })] : []),
    ],
  });
}

// Bullet με βέλος
function bullet(boldPart, rest = '') {
  return new Paragraph({
    spacing: { before: 50, after: 40 },
    indent:  { left: convertInchesToTwip(0.35) },
    children: [
      new TextRun({ text: '►  ', font: F, size: SZ.body, bold: true }),
      new TextRun({ text: boldPart, font: F, size: SZ.body, bold: true }),
      ...(rest ? [new TextRun({ text: `  ${rest}`, font: F, size: SZ.body })] : []),
    ],
  });
}

// Κουτί ΠΡΟΣΟΧΗ
function warn(text) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: { top: BOX_BORDER.top, bottom: BOX_BORDER.bottom, left: BOX_BORDER.left, right: BOX_BORDER.right,
               insideH: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
               insideV: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' } },
    rows: [new TableRow({
      children: [new TableCell({
        borders: BOX_BORDER,
        margins: { left: 200, right: 200, top: 120, bottom: 120 },
        children: [new Paragraph({
          children: [
            new TextRun({ text: '⚠  ΠΡΟΣΟΧΗ:  ', font: F, size: SZ.body, bold: true }),
            new TextRun({ text, font: F, size: SZ.body }),
          ],
        })],
      })],
    })],
  });
}

// Κουτί ΣΗΜΕΙΩΣΗ
function note(text) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: { top: THIN_BOX.top, bottom: THIN_BOX.bottom, left: THIN_BOX.left, right: THIN_BOX.right,
               insideH: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
               insideV: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' } },
    rows: [new TableRow({
      children: [new TableCell({
        borders: THIN_BOX,
        margins: { left: 180, right: 180, top: 100, bottom: 100 },
        children: [new Paragraph({
          children: [
            new TextRun({ text: '✓  ', font: F, size: SZ.body, bold: true }),
            new TextRun({ text, font: F, size: SZ.body, italic: true }),
          ],
        })],
      })],
    })],
  });
}

// Κουτί ΠΛΗΡΟΦΟΡΙΑΣ (για πλάνα, τιμές, κλπ)
function infoBox(lines) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: { top: THIN_BOX.top, bottom: THIN_BOX.bottom, left: THIN_BOX.left, right: THIN_BOX.right,
               insideH: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' },
               insideV: { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' } },
    rows: [new TableRow({
      children: [new TableCell({
        borders: THIN_BOX,
        margins: { left: 180, right: 180, top: 100, bottom: 100 },
        children: lines.map(([bold, rest]) => new Paragraph({
          spacing: { before: 40, after: 40 },
          children: [
            new TextRun({ text: bold, font: F, size: SZ.body, bold: true }),
            ...(rest ? [new TextRun({ text: `  ${rest}`, font: F, size: SZ.body })] : []),
          ],
        })),
      })],
    })],
  });
}

